let activeLanguage = 'fr';

function browserLanguage() {
  return globalThis.navigator?.language || 'fr';
}

export function normalizeUiLanguagePreference(value) {
  return UI_LANGUAGE_PREFERENCES.includes(value) ? value : 'auto';
}

export function resolveUiLanguage(preference = 'auto', locale = browserLanguage()) {
  const normalized = normalizeUiLanguagePreference(preference);
  if (normalized !== 'auto') return normalized;
  return String(locale).toLowerCase().startsWith('en') ? 'en' : 'fr';
}

export function setUiLanguage(preference = 'auto', locale = browserLanguage()) {
  activeLanguage = resolveUiLanguage(preference, locale);
  return activeLanguage;
}

export function getUiLanguage() {
  return activeLanguage;
}

export function createTranslator(language = activeLanguage) {
  const selected = messages[language] || messages.fr;
  return (key, values = {}) => {
    const template = selected[key] ?? messages.fr[key] ?? key;
    return String(template).replace(/\{(\w+)\}/g, (_match, name) => (
      Object.hasOwn(values, name) ? String(values[name]) : `{${name}}`
    ));
  };
}

export function translationKeys(language) {
  return Object.keys(messages[language] || {}).sort();
}

export function t(key, values = {}) {
  return createTranslator(activeLanguage)(key, values);
}

export function applyDocumentTranslations(root = document) {
  root.documentElement.lang = activeLanguage;
  for (const node of root.querySelectorAll('[data-i18n]')) {
    const values = {};
    for (const [name, value] of Object.entries(node.dataset)) {
      if (name.startsWith('i18n') && name !== 'i18n') {
        values[name.slice(4).toLowerCase()] = value;
      }
    }
    node.textContent = t(node.dataset.i18n, values);
  }
  for (const node of root.querySelectorAll('[data-i18n-title]')) {
    node.title = t(node.dataset.i18nTitle);
  }
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  }
  for (const node of root.querySelectorAll('[data-i18n-aria-label]')) {
    node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel));
  }
  for (const node of root.querySelectorAll('[data-i18n-alt]')) {
    node.alt = t(node.dataset.i18nAlt);
  }
}
